import statsmodels.api as sm

scenarios = [1.5, 2.0, 2.5, 3.0]
rows = []
for name in ["DJF", "MAM"]:
    for zname, zmask in zones.items():
        d = prep(name, zmask, 1979)
        m = sm.OLS(d["pr"], sm.add_constant(d["oni"])).fit()
        for s in scenarios:
            f = m.get_prediction(np.array([[1.0, s]])).summary_frame(alpha=0.2)
            mean = float(f["mean"].iloc[0])
            rows.append({
                "сезон": name, "зона": zname, "ONI": s,
                "ожид. откл., %": round(mean, 1),
                "80% интервал": f"{f['obs_ci_lower'].iloc[0]:.0f} ... {f['obs_ci_upper'].iloc[0]:.0f}",
                "P(выше нормы)": round(float(stats.norm.cdf(mean / np.sqrt(m.scale))), 2),
                "r": round(np.sqrt(m.rsquared) * np.sign(m.params["oni"]), 2),
            })
display(pd.DataFrame(rows))